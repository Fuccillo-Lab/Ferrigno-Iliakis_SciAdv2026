%% LOCAL HELPER FUNCTIONS



function S = loadStreamByRow(h5file, row, which)
% which: "unfiltered" | "debleached" | "normalized"
switch which
    case "unfiltered", pSig = row.path_unfiltered;
    case "debleached", pSig = row.path_debleached;
    case "normalized", pSig = row.path_normalized;
    otherwise, error("Unknown which=%s", which);
end

S.signal = h5read(h5file, pSig);
S.time   = h5read(h5file, row.path_time);
end



function [X, tRel] = extractAligned(S, eventTimes, win)
fs   = 1/median(diff(S.time));
tRel = win(1):1/fs:win(2);

nT = numel(eventTimes);
nS = numel(tRel);
X  = nan(nT, nS);

for i = 1:nT
    t0 = eventTimes(i);
    if isnan(t0), continue; end
    tq = t0 + tRel;
    X(i,:) = interp1(S.time, S.signal, tq, "linear", NaN);
end
end

function tr = trialsForStream(trials, streamsRow)
tr = trials(trials.session_uid == streamsRow.session_uid & ...
    trials.animal_id   == streamsRow.animal_id, :);
end

function [h,meta,single] = plotPhotometryQuery(streams, trials, h5file, varargin)

p = inputParser;
addParameter(p, "cell_type", "any");        % "d1" | "a2a" | "any"
addParameter(p, "align", "tone_start");     % "trial_start" | "tone_start" | "outcome"
addParameter(p, "which", "debleached");     % "unfiltered" | "debleached" | "normalized"
addParameter(p, "win", [-2 2]);             % seconds
addParameter(p, "outcome", "any");          % "hit"|"miss"|"cr"|"fa"|...
addParameter(p, "tone_type", "any");        % "go"|"nogo"|"any"
addParameter(p, "task_phase", "any");       % 3 or 13 or "any"
addParameter(p, "go_is_high", "any");       % 0/1 or "any"
addParameter(p, "side", "any");             % "L"|"R"|"unused"|"any"
addParameter(p, "exclude_nrxn", true);      % default exclude
addParameter(p, "max_streams", inf);
addParameter(p, "max_trials_per_stream", inf);
addParameter(p, "plot_individual", false);  % start clean
addParameter(p, "weight_by", "trial");      % "trial" or "stream" (see note)
addParameter(p, "Color", [0 0 0]);     % RGB, 0–1 or 0–255
addParameter(p, "FillAlpha", 0.15);    % transparency for SEM band
addParameter(p, "perf_only", true);   % default: only hit/miss/cr/fa
addParameter(p, "tone_freq", "any");  % "high" | "low" | "any"
addParameter(p, "return_single_trials", false);
addParameter(p, "sort_by", "none");   % "rt" | "peak" | "baseline" | "trial_index"
addParameter(p, "peak_win", [0 0.25]);
addParameter(p, "base_win", [-0.5 0]);

parse(p, varargin{:});
o = p.Results;

S = streams;
single = struct();


% basic stream filters
S = S(S.has_signal==true, :);
if o.exclude_nrxn
    S = S(S.nrxn==0, :);
end
if o.cell_type ~= "any"
    S = S(S.cell_type == o.cell_type, :);
end
if o.task_phase ~= "any"
    S = S(S.task_phase == o.task_phase, :);
end
if o.go_is_high ~= "any"
    S = S(S.go_is_high == o.go_is_high, :);
end
if o.side ~= "any"
    S = S(S.side == o.side, :);
end



if height(S)==0
    error("No streams match the requested filters.");
end

S = S(1:min(height(S), o.max_streams), :);

% collect aligned matrices in a cell (avoid slow growing arrays)
Xc = cell(height(S),1);
streamAnimal = cell(height(S),1);
streamSide = cell(height(S),1);
tc = [];
keepStream = false(height(S),1);
inc = table();
inc.stream_uid   = strings(0,1);
inc.animal_id    = strings(0,1);
inc.session_uid  = strings(0,1);
inc.side         = strings(0,1);
inc.n_trials     = zeros(0,1);

if o.return_single_trials
    allX = zeros(0,0);          % will set after first stream determines nSamples
    allRT = []; allPeak = []; allBase = [];
    allOutcome = strings(0,1);
    allToneType = strings(0,1);
    allToneFreq = strings(0,1); % optional
    allAnimal = strings(0,1);
    allSession = strings(0,1);
    allStream = strings(0,1);
    allSide = strings(0,1);
    allGoIsHigh = [];           % numeric
end


for k = 1:height(S)
    row = S(k,:);
    sig = loadStreamByRow(h5file, row, o.which);

    % trials for this stream (join by session_uid + animal_id)
    tr = trials(trials.session_uid == row.session_uid & trials.animal_id == row.animal_id, :);

    % trial filters
    tr = tr(tr.is_valid==true, :);
    if o.exclude_nrxn && ismember("nrxn", tr.Properties.VariableNames)
        tr = tr(tr.nrxn==0, :);
    end
    % If you only want performance trials (hit/miss/cr/fa)
    if o.perf_only
        tr = tr(ismember(tr.outcome, ["hit","miss","cr","fa"]), :);
    end
    if o.outcome ~= "any"
        tr = tr(tr.outcome == o.outcome, :);
    end
    if o.tone_type ~= "any"
        tr = tr(tr.tone_type == o.tone_type, :);
    end
    % ---- NEW: filter by physical tone frequency (high/low) ----
    if o.tone_freq ~= "any"
        if ~ismember("go_is_high", tr.Properties.VariableNames)
            error("trials table is missing variable 'go_is_high' needed for tone_freq filtering.");
        end

        % derive physical frequency for each trial
        tf = strings(height(tr),1);  % "high"/"low"/""
        isGo   = tr.tone_type == "go";
        isNoGo = tr.tone_type == "nogo";

        % Go trials: go_is_high maps directly
        tf(isGo  & tr.go_is_high==1) = "high";
        tf(isGo  & tr.go_is_high==0) = "low";

        % NoGo trials: opposite mapping
        tf(isNoGo & tr.go_is_high==1) = "low";
        tf(isNoGo & tr.go_is_high==0) = "high";

        % If there are other tone_type values, they stay "" and will be dropped by the filter below.
        tr = tr(tf == o.tone_freq, :);
    end



    if height(tr)==0
        continue
    end

    % alignment times
    switch o.align
        case "trial_start", ev = tr.t_trial_start;
        case "tone_start",  ev = tr.t_tone_start;
        case "outcome",     ev = tr.t_outcome;
        otherwise, error("Unknown align=%s", o.align);
    end

    % subsample trials if requested
    if isfinite(o.max_trials_per_stream) && height(tr) > o.max_trials_per_stream
        ix = randperm(height(tr), o.max_trials_per_stream);
        ev = ev(ix);
    end

    [X, tRel] = extractAligned(sig, ev, o.win);

    % 4) define keepTrial NOW
    fracNaN   = mean(isnan(X),2);
    keepTrial = fracNaN < 0.2;
    
    % 5) apply keepTrial to BOTH X and tr
    X  = X(keepTrial,:);
    tr = tr(keepTrial,:);
    if isempty(X), continue; end
    tc = tRel;

    if o.return_single_trials

        % 1) Compute RT relative to tone (only meaningful for Go responses; others -> NaN)
        % Define RT as outcome - tone_start (since outcome==first lick for go trials)
        rt = tr.t_outcome - tr.t_tone_start;     % height(tr) x 1
        rt = rt(keepTrial);                      % align with X rows

        % 2) Peak and baseline from X in windows
        pkIx = tc >= o.peak_win(1) & tc <= o.peak_win(2);
        bsIx = tc >= o.base_win(1) & tc <= o.base_win(2);

        peakVal = max(X(:, pkIx), [], 2, "omitnan");     % nKept x 1 (or mean)
        baseVal = mean(X(:, bsIx), 2, "omitnan");        % nKept x 1

        % 3) Trial labels (aligned)
        out = string(tr.outcome);
        out = out(keepTrial);

        tt = string(tr.tone_type);
        tt = tt(keepTrial);

        gih = tr.go_is_high;
        gih = gih(keepTrial);

        % optional: derived physical tone freq (high/low)
        tf = strings(numel(tt),1);
        isGo   = tt == "go";
        isNoGo = tt == "nogo";
        tf(isGo   & gih==1) = "high";
        tf(isGo   & gih==0) = "low";
        tf(isNoGo & gih==1) = "low";
        tf(isNoGo & gih==0) = "high";

        % 4) Stream-level IDs replicated per trial
        nKept = size(X,1);
        animal = repmat(string(row.animal_id),  nKept, 1);
        sess   = repmat(string(row.session_uid), nKept, 1);
        stream = repmat(string(row.stream_uid),  nKept, 1);
        side   = repmat(string(row.side),        nKept, 1);

        % 5) Concatenate into “all*” accumulators
        if isempty(allX)
            allX = X;
        else
            allX = [allX; X];
        end
        allRT      = [allRT; rt];
        allPeak    = [allPeak; peakVal];
        allBase    = [allBase; baseVal];
        allOutcome = [allOutcome; out];
        allToneType= [allToneType; tt];
        allToneFreq= [allToneFreq; tf];
        allGoIsHigh= [allGoIsHigh; gih];
        allAnimal  = [allAnimal; animal];
        allSession = [allSession; sess];
        allStream  = [allStream; stream];
        allSide    = [allSide; side];
    end



    Xc{k} = X;
    streamAnimal{k} = row.animal_id;
    streamSide{k}   = row.side;

    keepStream(k) = true;
    nUsed = size(X,1);
    if nUsed > 0
        inc = [inc; table(row.stream_uid, row.animal_id, row.session_uid, row.side, nUsed, ...
            'VariableNames', ["stream_uid","animal_id","session_uid","side","n_trials"])];
    end
end

Xc = Xc(keepStream);
if isempty(Xc)
    error("No trials survived filtering across all matching streams.");
else
    streamAnimal = streamAnimal(keepStream);
    streamSide   = streamSide(keepStream);
end
if o.return_single_trials
    single.X = allX;
    single.t = tc;
    single.rt = allRT;
    single.peak = allPeak;
    single.base = allBase;
    single.outcome = allOutcome;
    single.tone_type = allToneType;
    single.tone_freq = allToneFreq;
    single.go_is_high = allGoIsHigh;
    single.animal_id = allAnimal;
    single.session_uid = allSession;
    single.stream_uid = allStream;
    single.side = allSide;
    single.cell_type = repmat(string(o.cell_type), size(allX,1), 1); % or leave blank if "any"
end

if o.return_single_trials && o.sort_by ~= "none"
    switch o.sort_by
        case "rt",       key = single.rt;
        case "peak",     key = single.peak;
        case "baseline", key = single.base;
        case "trial_index", key = (1:size(single.X,1))';
        otherwise, key = [];
    end

    if ~isempty(key)
        [~,ord] = sort(key, "ascend", "MissingPlacement","last");
        f = fieldnames(single);
        for i = 1:numel(f)
            v = single.(f{i});
            if isvector(v) && numel(v) == size(single.X,1)
                single.(f{i}) = v(ord,:);
            end
        end
        single.X = single.X(ord,:);
    end
end








switch o.weight_by

    case "trial"
        % all trials pooled
        allX = vertcat(Xc{:});
        m = mean(allX, 1, "omitnan");
        s = std(allX, 0, 1, "omitnan") ./ sqrt(sum(~isnan(allX),1));
        nLabel = size(allX,1) + " trials";

    case "stream"
        % one trace per stream
        streamMeans = cellfun(@(x) mean(x,1,"omitnan"), Xc, "UniformOutput", false);
        M = vertcat(streamMeans{:}); % nStreams x nSamples
        m = mean(M, 1, "omitnan");
        s = std(M, 0, 1, "omitnan") ./ sqrt(size(M,1));
        nLabel = size(M,1) + " streams";

    case "animal"
        % ----- NEW: hierarchical animal averaging -----

        % 1) mean within each stream
        streamMeans = cellfun(@(x) mean(x,1,"omitnan"), Xc, "UniformOutput", false);
        Mstream = vertcat(streamMeans{:}); % nStreams x nSamples
        
        % --- NEW: store stream-level outputs for stats ---
        meta.stream_traces = Mstream;
        meta.stream_uid    = string(inc.stream_uid);   % one row per stream
        meta.animal_id     = string(inc.animal_id);
        meta.session_uid   = string(inc.session_uid);
        meta.side          = string(inc.side);

        % (optional sanity)
        assert(size(Mstream,1) == numel(meta.stream_uid), 'Mstream rows must match inc rows.');

        animalVec = string(streamAnimal);   % convert cell -> string
        % 2) group streams by animal
        [Ga, animalList] = findgroups(animalVec);

        % 3) mean across streams within each animal
        Manimal = splitapply(@(rows) mean(rows,1,"omitnan"), Mstream, Ga);

        % 4) mean + SEM across animals
        m = mean(Manimal, 1, "omitnan");
        s = std(Manimal, 0, 1, "omitnan") ./ sqrt(size(Manimal,1));
        nLabel = size(Manimal,1) + " animals";

    otherwise
        error("Unknown weight_by=%s", o.weight_by);
end

meta.included = inc;
meta.n_streams = height(unique(inc(:, "stream_uid")));
meta.n_animals = numel(unique(inc.animal_id));
meta.n_sessions = numel(unique(inc.session_uid));
meta.n_trials = sum(inc.n_trials);
meta.animal_list  = animalList;
meta.n_animals    = numel(animalList);
meta.animal_traces = Manimal;  % useful for stats later



% plot
% if nargout == 0
%     figure; hold on;
% end

h = plotMeanSEM(tc, m, s, o.Color, ...
    "FillAlpha", o.FillAlpha);

xline(0, "--");
xlabel("Time (s)");
ylabel(o.which);

title(sprintf("cell=%s align=%s outcome=%s tone=%s phase=%s (%s)", ...
    o.cell_type, o.align, o.outcome, o.tone_type, ...
    string(o.task_phase), nLabel));
end

