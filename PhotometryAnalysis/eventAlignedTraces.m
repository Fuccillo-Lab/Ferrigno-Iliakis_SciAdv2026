% ---------- D1: build AUC table from your existing meta vars ----------
t = -2:0.025:2;            % make sure meta.t = tc in plotPhotometryQuery
t0 = 0.15;  tEnd = 1.15;
tMid = (t0 + tEnd)/2;              % or pick a biologically motivated split

A_D1_hit = auc2bins_stream(t, metaToStartD1hit.stream_traces, t0, tMid, tEnd);
A_D1_fa  = auc2bins_stream(t, metaToStartD1FA.stream_traces,  t0, tMid, tEnd);
A_D1_cr  = auc2bins_stream(t, metaToStartD1CR.stream_traces,  t0, tMid, tEnd);

% helper to make long-format rows (stream-level)
mkBlock = @(meta, A, outLabel) table( ...
    repmat(categorical(string(outLabel), ["hit","fa","cr"]), size(A,1)*2, 1), ...
    repmat(string(meta.animal_id),   2, 1), ...
    repmat(string(meta.session_uid), 2, 1), ...
    repmat(string(meta.stream_uid),  2, 1), ...
    [repmat(categorical("early",["early","late"]), size(A,1),1); repmat(categorical("late",["early","late"]), size(A,1),1)], ...
    [A(:,1); A(:,2)], ...
    'VariableNames', {'outcome','animal_id','session_uid','stream_uid','timebin','auc'} );

T_D1 = [ ...
    mkBlock(metaToStartD1hit, A_D1_hit, "hit"); ...
    mkBlock(metaToStartD1FA,  A_D1_fa,  "fa");  ...
    mkBlock(metaToStartD1CR,  A_D1_cr,  "cr")   ...
];

% ---------- LME per time bin (cleanest, matches your kernel AUC logic) ----------
T_D1_early = T_D1(T_D1.timebin=="early",:);
lme_D1_E = fitlme(T_D1_early, 'auc ~ outcome + (1|animal_id)');
anova_D1_E = anova(lme_D1_E, 'DFMethod','Satterthwaite')

C_cr_hit = [0 1 0];
[p_cr_hit, F_cr_hit] = coefTest(lme_D1_E, C_cr_hit);

C_fa_hit = [0 0 1];
[p_fa_hit, F_fa_hit] = coefTest(lme_D1_E, C_fa_hit);

C_fa_cr = [0 -1 1];
[p_fa_cr, F_fa_cr] = coefTest(lme_D1_E, C_fa_cr);

T_D1_late = T_D1(T_D1.timebin=="late",:);
lme_D1_L = fitlme(T_D1_late, 'auc ~ outcome + (1|animal_id)');
anova_D1_L = anova(lme_D1_L, 'DFMethod','Satterthwaite')

t = -2:0.025:2;

baseIx = t>=-0.5 & t<=0;
peakIx = t>=0    & t<=0.4;

% robust-ish peak: mean of top k samples
k = 5;

peakMetric = @(M) ...
    mean(maxk(M(:,peakIx), k, 2), 2) - mean(M(:,baseIx), 2);

% D1 metrics per outcome (one value per stream)
yD1_hit = peakMetric(metaToStartD1hit.stream_traces);
