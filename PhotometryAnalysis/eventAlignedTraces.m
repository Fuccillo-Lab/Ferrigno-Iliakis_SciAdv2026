function T = streamFullTraceStats(streams, h5file, which)
if nargin < 3, which = "debleached"; end

T = streams(:, ["stream_uid","animal_id","session_uid","cell_type","task_phase","side","go_is_high"]);
T.mu = nan(height(T),1);
T.sd = nan(height(T),1);
T.n  = zeros(height(T),1);
T.medx = nan(height(T),1);
T.sdrob = nan(height(T),1);
T.p95 = nan(height(T),1);
T.largeEventRate = nan(height(T),1);

for k = 1:height(T)
    row = streams(k,:);
    S = loadStreamByRow(h5file, row, which);
    x = S.signal;
    mu = mean(x, "omitnan");
    T.mu(k) = mu;
    sd = std(x, 0, "omitnan");
    T.sd(k) = sd;
    T.n(k)  = sum(~isnan(x));
    medx = median(x,"omitnan");
    T.medx(k) = medx;
    xnn = x(~isnan(x));
    if isempty(xnn)
        sdrob = NaN;
    else
        medx_local = median(xnn);
        sdrob = 1.4826 * median(abs(xnn - medx_local));
    end

    T.sdrob(k) = sdrob;
    p95 = prctile(x(~isnan(x)),95);
    T.p95(k) = p95;
    const = 4;
    T.largeEventConst(k) = const;
    T.largeEventRate(k) = mean(x > medx + const*sdrob,'omitnan');
end
end




function [xD1, xA2A] = collectSignalsByCellType(streams, h5file, which)
if nargin < 3, which = "debleached"; end

isD1  = streams.cell_type == "d1";
isA2A = streams.cell_type == "a2a";   % adjust if your labels differ

xD1  = [];
xA2A = [];

for k = 1:height(streams)
    S = loadStreamByRow(h5file, streams(k,:), which);
    x = S.signal;
    x = x(~isnan(x));
    if isempty(x), continue; end

    if isD1(k)
        xD1 = [xD1; x(:)];
    elseif isA2A(k)
        xA2A = [xA2A; x(:)];
    end
end
end

function auc2 = auc2bins_stream(t, Mstream, t0, tMid, tEnd)
% t: 1 x nTime (or nTime x 1)
% Mstream: nStreams x nTime
% auc2: nStreams x 2  (early, late)

t = t(:)';  % row
ixE = t>=t0   & t<tMid;
ixL = t>=tMid & t<=tEnd;

aucE = trapz(t(ixE), Mstream(:,ixE), 2);
aucL = trapz(t(ixL), Mstream(:,ixL), 2);

auc2 = [aucE, aucL];
end


function h = plot_peak_triplet_by_animal(Tpk, titleStr)
% Tpk must have vars: outcome, animal_id, session_uid, stream_uid, peak
% outcome values expected: 'hit','fa','cr' (case-insensitive ok)

% --- sanitize outcomes
out = lower(string(Tpk.outcome));
Tpk.outcome = categorical(out);

% Keep only the three outcomes we care about
keep = ismember(Tpk.outcome, categorical(["hit","fa","cr"]));
T = Tpk(keep,:);

% --- 1) collapse streams within a session (animal × session × outcome)
G1 = findgroups(T.animal_id, T.session_uid, T.outcome);
peak_sess = splitapply(@mean, T.peak, G1);

animal_sess = splitapply(@(x)x(1), string(T.animal_id), G1);
sess_uid    = splitapply(@(x)x(1), string(T.session_uid), G1);
outcome     = splitapply(@(x)x(1), T.outcome, G1);

Tsess = table(animal_sess, sess_uid, outcome, peak_sess, ...
    'VariableNames', {'animal_id','session_uid','outcome','peak'});

% --- 2) collapse sessions within animal (animal × outcome) -> one dot per animal per condition
G2 = findgroups(Tsess.animal_id, Tsess.outcome);
peak_animal = splitapply(@mean, Tsess.peak, G2);

animal_id = splitapply(@(x)x(1), Tsess.animal_id, G2);
outcome2  = splitapply(@(x)x(1), Tsess.outcome, G2);

Tanimal = table(string(animal_id), outcome2, peak_animal, ...
    'VariableNames', {'animal_id','outcome','peak'});

% --- pivot to wide: one row per animal, columns hit/fa/cr
animals = unique(Tanimal.animal_id);
Y = nan(numel(animals),3); % [hit fa cr]

for i = 1:numel(animals)
    a = animals(i);
    for j = 1:3
        lab = ["hit","fa","cr"];
        idx = (Tanimal.animal_id==a) & (Tanimal.outcome==categorical(lab(j)));
        if any(idx)
            Y(i,j) = Tanimal.peak(find(idx,1,'first'));
        end
    end
end

% optionally drop animals missing any condition
valid = all(isfinite(Y),2);
Y = Y(valid,:);
animals = animals(valid);

% --- compute group mean and SEM
mu  = mean(Y,1,'omitnan');
sem = std(Y,0,1,'omitnan') ./ sqrt(sum(isfinite(Y),1));

% --- plot
x = 1:3; % hit, fa, cr

h = figure('Color','w'); hold on;

% thin lines per animal
for i = 1:size(Y,1)
    plot(x, Y(i,:), '-', 'Color', [0.7 0.7 0.7], 'LineWidth', 0.75);
end

% animal points
for j = 1:3
    scatter(ones(size(Y,1),1)*x(j), Y(:,j), 28, ...
        'MarkerFaceColor',[0.5 0.5 0.5], 'MarkerEdgeColor','none', ...
        'MarkerFaceAlpha', 0.75);
end

% group mean ± SEM (big black)
errorbar(x, mu, sem, 'k', 'LineWidth', 2, 'CapSize', 10);
scatter(x, mu, 80, 'k', 'filled');

% cosmetics
set(gca,'XLim',[0.5 3.5], 'XTick', x, 'XTickLabel', {'Hit','FA','CR'});
ylabel('Peak (a.u.)');
title(sprintf('%s (n=%d animals)', titleStr, size(Y,1)));
box off; set(gca,'LineWidth',1.2);

% optional: add a zero line
yline(0,'--','Color',[0.6 0.6 0.6]);

end